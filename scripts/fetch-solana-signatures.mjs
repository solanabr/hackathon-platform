import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const RPC_URL = "https://api.mainnet-beta.solana.com";
const TOKEN_PROGRAM = "TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA";
const BASE58 =
  "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";
const OUT_PATH = join(
  __dirname,
  "../src/components/home/colosseum/signatures.generated.ts",
);

function isBase58(value) {
  for (const char of value) {
    if (!BASE58.includes(char)) return false;
  }
  return true;
}

async function main() {
  let response;
  try {
    response = await fetch(RPC_URL, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        jsonrpc: "2.0",
        id: 1,
        method: "getSignaturesForAddress",
        params: [TOKEN_PROGRAM, { limit: 1000 }],
      }),
    });
  } catch (error) {
    console.error("RPC request failed:", error);
    process.exit(1);
  }

  if (!response.ok) {
    console.error(`RPC HTTP ${response.status}: ${response.statusText}`);
    process.exit(1);
  }

  let payload;
  try {
    payload = await response.json();
  } catch (error) {
    console.error("RPC response is not valid JSON:", error);
    process.exit(1);
  }

  if (payload.error) {
    console.error("RPC error:", payload.error);
    process.exit(1);
  }

  const { result } = payload;
  if (!Array.isArray(result) || result.length === 0) {
    console.error("RPC returned no signatures");
    process.exit(1);
  }

  const signatures = result.map((item) => item?.signature).filter(Boolean);
  if (signatures.length === 0) {
    console.error("No signature strings in RPC result");
    process.exit(1);
  }

  const buffer = signatures.join("");
  if (!isBase58(buffer)) {
    console.error(
      "Signature buffer contains invalid base58 characters — aborting",
    );
    process.exit(1);
  }

  const content = `// Generated by scripts/fetch-solana-signatures.mjs — do not edit by hand.
export const SIGNATURE_BUFFER = "${buffer}";
`;

  writeFileSync(OUT_PATH, content, "utf8");
  console.log(`Wrote ${buffer.length} base58 characters to ${OUT_PATH}`);
}

main();
